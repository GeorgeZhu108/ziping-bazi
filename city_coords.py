def _normalize(name: str) -> str:
    """去空格与行政区划后缀，便于匹配。"""
    if not name:
        return ""
    s = name.strip()
    # 去常见后缀（顺序：长的先去）
    for suffix in ("特别行政区", "自治区", "自治州", "自治县", "地区", "新区",
                   "市辖区", "市", "县", "区", "省", "州", "盟", "旗"):
        if s.endswith(suffix) and len(s) > len(suffix):
            s = s[: -len(suffix)]
    # 去空格
    s = s.replace(" ", "").replace("　", "")
    return s


# 构建归一化索引：归一化名 -> (展示名, 经度, 纬度)
_INDEX = {}
for _name, (_lon, _lat) in _RAW.items():
    _key = _normalize(_name)
    if _key and _key not in _INDEX:
        _INDEX[_key] = (_name, _lon, _lat)
    # 同时保留"市/省"全称也能直接命中
    if _name not in _INDEX:
        _INDEX[_name] = (_name, _lon, _lat)


def lookup(city: str):
    """
    后台查询城市经纬度。
    返回 {"found": bool, "name": str, "longitude": float, "latitude": float}
    """
    if not city or not str(city).strip():
        return {"found": False, "name": "", "longitude": None, "latitude": None}

    q = _normalize(city)
    if not q:
        return {"found": False, "name": "", "longitude": None, "latitude": None}

    # 1) 精确匹配（归一化后）
    if q in _INDEX:
        name, lon, lat = _INDEX[q]
        return {"found": True, "name": name, "longitude": lon, "latitude": lat}

    # 2) 模糊包含匹配：查询包含库名，或库名包含查询
    candidates = []
    for key, (name, lon, lat) in _INDEX.items():
        if q in key or key in q:
            candidates.append((name, lon, lat))
    if candidates:
        # 取最短（最精确）的候选
        name, lon, lat = min(candidates, key=lambda c: len(c[0]))
        return {"found": True, "name": name, "longitude": lon, "latitude": lat}

    return {"found": False, "name": "", "longitude": None, "latitude": None}


