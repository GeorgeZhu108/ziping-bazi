# 将引擎识别出的格局名映射到子平真诠的「善/不善 + 顺逆喜忌」（取前2字匹配）
def ziping_ge_category(pattern_name: str):
    if not pattern_name:
        return None
    name = pattern_name.replace("格", "")[:2] + "格" if "格" in pattern_name else pattern_name
    for g in ZIPING_GE["善格"]:
        if name.startswith(g.replace("格", "")) or pattern_name.startswith(g):
            return {"category": "善格", "type": g, "policy": "顺用",
                    "note": ZIPING_GE["顺用"].get(g, ""), "source": ZIPING_GE["source"]}
    for g in ZIPING_GE["不善格"]:
        if name.startswith(g.replace("格", "")) or pattern_name.startswith(g):
            return {"category": "不善格", "type": g, "policy": "逆用",
                    "note": ZIPING_GE["逆用"].get(g, ""), "source": ZIPING_GE["source"]}
    return None


