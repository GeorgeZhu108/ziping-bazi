def _fmt_liang(qian: int):
    """钱 -> 'X两Y钱' 中文。"""
    liang, q = divmod(qian, 10)
    if liang and q:
        return f"{liang}两{q}钱"
    if liang:
        return f"{liang}两"
    return f"{q}钱"


def calculate_chengu(year_ganzhi: str, month: int, day: int, hour_zhi: str):
    """计算称骨。

    参数：
      year_ganzhi：年柱干支，如 "庚午"
      month：农历/公历月份（1-12，称骨按出生月序，本软件以公历月代入，按传统月序）
      day：出生日（1-30）
      hour_zhi：出生时辰地支，如 "巳"
    返回：{year_w, month_w, day_w, hour_w(均为钱), total_qian, total_str, song, song_band}
    """
    yw = YEAR_WEIGHT.get(year_ganzhi)
    mw = MONTH_WEIGHT.get(month)
    dw = DAY_WEIGHT.get(day)
    hw = HOUR_WEIGHT.get(hour_zhi)
    # 任一缺失则无法完整称骨
    if yw is None or mw is None or dw is None or hw is None:
        return {
            "year_w": yw, "month_w": mw, "day_w": dw, "hour_w": hw,
            "total_qian": None, "total_str": None,
            "song": "（称骨所需干支/月日时不全，无法完整计算）", "song_band": None,
            "source": "袁天罡称骨歌",
        }
    total = yw + mw + dw + hw
    song = SONG.get(total, "（此骨重超出常规批语范围，仅作参考）")
    return {
        "year_w": yw, "month_w": mw, "day_w": dw, "hour_w": hw,
        "total_qian": total,
        "total_str": _fmt_liang(total),
        "song": song,
        "song_band": total,
        "source": "袁天罡称骨歌",
    }


